"""
Ground Truth Verification Tool
Compares an export (JSON lines from `pipeline export`) with the ground truth mathematical model
generated by the given mode and seed.

Checks:
1. Every sample received is unchanged from the mathematical ground truth.
2. Every missing sample is accounted for in a loss record.
3. No silent data loss (unaccounted gaps).
4. No duplicate samples.
5. No invented values.
"""

import argparse
import json
import sys
from typing import Dict, List, Set, Tuple
from mock.mock_server import BiosignalGenerator

def verify_export(export_file: str, mode: str, seed: int, max_expected_samples: int = None) -> bool:
    generator = BiosignalGenerator(mode=mode, seed=seed)
    
    samples_found: Dict[int, Dict[int, List[int]]] = {1: {}, 2: {}}
    losses_found: Dict[int, List[Tuple[int, Optional[int], str]]] = {1: [], 2: []}
    
    total_lines = 0
    duplicate_count = 0
    corrupt_value_count = 0
    
    with open(export_file, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            total_lines += 1
            try:
                record = json.loads(line)
            except Exception as e:
                print(f"[ERROR] Line {line_num}: invalid JSON: {e}")
                return False
                
            if "index" in record:
                # Sample record: {"sensor": 1, "index": 120000, "values": [720, 1200, 1560]}
                s = record["sensor"]
                idx = record["index"]
                vals = record["values"]
                
                if idx in samples_found[s]:
                    print(f"[VIOLATION] Duplicate sample found! Sensor {s}, index {idx}")
                    duplicate_count += 1
                else:
                    samples_found[s][idx] = vals
                    
                # Verify values match ground truth
                if s == 1:
                    expected = generator.generate_sensor1_sample(idx)
                else:
                    expected = generator.generate_sensor2_sample(idx)
                    
                if vals != expected:
                    print(f"[VIOLATION] Value mismatch! Sensor {s}, index {idx}. Got {vals}, expected {expected}")
                    corrupt_value_count += 1
                    
            elif "from_index" in record:
                # Loss record: {"sensor": 2, "from_index": 4000, "to_index": 4399, "reason": "..."}
                s = record["sensor"]
                f_idx = record["from_index"]
                t_idx = record.get("to_index")
                reason = record.get("reason", "unknown")
                losses_found[s].append((f_idx, t_idx, reason))
            else:
                print(f"[WARNING] Unrecognized record on line {line_num}: {record}")
                
    print(f"--- Verification Summary for {export_file} ---")
    print(f"Total lines parsed: {total_lines}")
    print(f"Sensor 1 samples: {len(samples_found[1])}, losses reported: {len(losses_found[1])}")
    print(f"Sensor 2 samples: {len(samples_found[2])}, losses reported: {len(losses_found[2])}")
    
    success = True
    if duplicate_count > 0:
        print(f"[FAIL] {duplicate_count} duplicate samples detected!")
        success = False
    if corrupt_value_count > 0:
        print(f"[FAIL] {corrupt_value_count} corrupted or invented values detected!")
        success = False
        
    # Check for silent loss (gaps not covered by loss records)
    for s in (1, 2):
        if not samples_found[s]:
            continue
        min_idx = min(samples_found[s].keys())
        max_idx = max(samples_found[s].keys())
        if max_expected_samples is not None:
            max_idx = max(max_idx, max_expected_samples - 1)
            
        # Check every index in [min_idx, max_idx]
        silent_loss_count = 0
        for i in range(min_idx, max_idx + 1):
            if i not in samples_found[s]:
                # Must be covered by a loss record
                covered = False
                for (f_idx, t_idx, reason) in losses_found[s]:
                    if t_idx is None:
                        if i >= f_idx:
                            covered = True
                            break
                    else:
                        if f_idx <= i <= t_idx:
                            covered = True
                            break
                if not covered:
                    if silent_loss_count < 10:
                        print(f"[VIOLATION] Silent loss: Sensor {s}, index {i} is missing without a loss record!")
                    silent_loss_count += 1
                    
        if silent_loss_count > 0:
            print(f"[FAIL] Sensor {s} has {silent_loss_count} silent lost samples!")
            success = False

    if success:
        print("[SUCCESS] All criteria satisfied: 0 duplicates, 0 corrupt values, 0 silent losses!")
    return success

def main():
    parser = argparse.ArgumentParser(description="Check export against ground truth")
    parser.add_argument("export_file", help="Path to exported JSONL file")
    parser.add_argument("--mode", choices=["signal", "ramp"], default="signal", help="Generator mode")
    parser.add_argument("--seed", type=int, default=7, help="Seed used by mock")
    parser.add_argument("--expected-samples", type=int, default=None, help="Total expected samples")
    args = parser.parse_args()

    ok = verify_export(args.export_file, args.mode, args.seed, args.expected_samples)
    sys.exit(0 if ok else 1)

if __name__ == "__main__":
    main()
